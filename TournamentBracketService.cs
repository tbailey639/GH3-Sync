using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace GH3_Sync;

public record TournamentPlayer(string Name, string FriendCode, int Seed);

public record TournamentMatch(
    int MatchId,
    int Round,
    TournamentPlayer Player1,
    TournamentPlayer Player2,
    string? PickedSongTitle,
    string? BannedSong1,
    string? BannedSong2,
    long Player1Score,
    long Player2Score,
    TournamentPlayer? Winner
);

public class TournamentBracketService
{
    public record Tournament(
        string TournamentId,
        string Title,
        int PlayerCount,
        List<TournamentPlayer> Players,
        List<TournamentMatch> Matches,
        DateTime CreatedAt
    );

    public Tournament GenerateTournament(string title, List<string> playerNames, List<CustomSongInfo> songPool)
    {
        int count = playerNames.Count switch
        {
            >= 16 => 16,
            >= 8 => 8,
            _ => 4
        };

        var players = new List<TournamentPlayer>();
        for (int i = 0; i < count; i++)
        {
            string name = i < playerNames.Count ? playerNames[i] : $"Rocker {i + 1}";
            players.Add(new TournamentPlayer(name, $"GH3-{i + 1:D4}", i + 1));
        }

        var matches = new List<TournamentMatch>();
        int matchId = 1;
        var random = new Random();

        // Round 1
        for (int i = 0; i < count / 2; i++)
        {
            var p1 = players[i];
            var p2 = players[count - 1 - i]; // Standard 1 vs N seeding

            string? song = songPool.Count > 0 ? songPool[random.Next(songPool.Count)].Title : "Through the Fire and Flames";
            string? ban1 = songPool.Count > 1 ? songPool[random.Next(songPool.Count)].Title : "Raining Blood";
            string? ban2 = songPool.Count > 2 ? songPool[random.Next(songPool.Count)].Title : "One";

            matches.Add(new TournamentMatch(
                MatchId: matchId++,
                Round: 1,
                Player1: p1,
                Player2: p2,
                PickedSongTitle: song,
                BannedSong1: ban1,
                BannedSong2: ban2,
                Player1Score: 0,
                Player2Score: 0,
                Winner: null
            ));
        }

        return new Tournament(
            TournamentId: Guid.NewGuid().ToString("N")[..8],
            Title: title,
            PlayerCount: count,
            Players: players,
            Matches: matches,
            CreatedAt: DateTime.UtcNow
        );
    }

    public string ExportTournamentMarkdown(Tournament t)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# 🏆 {t.Title.ToUpperInvariant()} — TOURNAMENT BRACKET");
        sb.AppendLine($"*Generated by GH3-Sync Concert Master • {t.PlayerCount} Players Single Elimination*");
        sb.AppendLine();
        sb.AppendLine("| Match | Round | Player 1 | Player 2 | Selected Song | Vetoed Songs | Winner |");
        sb.AppendLine("|---|---|---|---|---|---|---|");

        foreach (var m in t.Matches)
        {
            string winner = m.Winner?.Name ?? "TBD";
            string vetoes = $"{m.BannedSong1} / {m.BannedSong2}";
            sb.AppendLine($"| #{m.MatchId} | R{m.Round} | **{m.Player1.Name}** | **{m.Player2.Name}** | 🎸 {m.PickedSongTitle} | 🚫 {vetoes} | 👑 {winner} |");
        }

        sb.AppendLine();
        sb.AppendLine("### ⚔️ Song Veto & Pick Rules:");
        sb.AppendLine("1. **Coin Toss**: Higher seed chooses pick order or ban order.");
        sb.AppendLine("2. **Bans**: Player 1 bans 1 song, Player 2 bans 1 song from the lobby setlist.");
        sb.AppendLine("3. **Picks**: The decider track is played in Head-to-Head Pro Face-Off.");
        sb.AppendLine("4. **Victory**: Player with highest score advances to the next round!");
        return sb.ToString();
    }
}
